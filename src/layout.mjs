/**
 * The document shell every page shares: head (metadata, language versions, fonts, styles, scripts, structured data),
 * the skip link, the navigation bar, the main landmark and the footer. All addresses are root-relative, so a page
 * works at any depth (GitHub Pages serves 404.html for any unknown path).
 */
import { attrs, esc, jsonForScript, need, t } from "./lib/html.mjs";
import { content } from "./content/index.mjs";
import { COMPANY, SITE } from "./content/site.mjs";
import { siteFooter } from "./components/site-footer.mjs";
import { siteNav } from "./components/site-nav.mjs";
import { DEFAULT_LOCALE, OG_LOCALE, alternates, currentLocale, pathOf, routeOf } from "./i18n/index.mjs";
import { END_ID, END_SCRIPT, HEAD_SCRIPT } from "./lib/lang-switch.mjs";

export const GENERATED_NOTE = "<!-- Generated by build.mjs from src/. Do not edit this file: change src/ and run `node build.mjs`. -->";

export const FONT_FILES = ["manrope-latin-wght-normal.woff2", "manrope-latin-ext-wght-normal.woff2"];

/** The share picture of each language (its headline is drawn into it). */
export const SHARE_IMAGE = { cs: "/assets/og.png", en: "/assets/og-en.png" };

/** The page's address as search engines should know it. */
export const canonical = (path) => `${SITE.origin}${path}`;

/** A language's home page keeps its own title; other pages add the site's name. */
export const fullTitle = (path, title) => (routeOf(path)?.key === "home" ? title : `${title} | ${SITE.name}`);

export function organizationJsonLd() {
  return {
    "@context": "https://schema.org",
    "@type": "Organization",
    name: COMPANY.legalName,
    url: content().cognera.home,
    address: { "@type": "PostalAddress", streetAddress: COMPANY.address.street, postalCode: COMPANY.address.postalCode, addressLocality: COMPANY.address.city, addressCountry: "CZ" },
  };
}

export function websiteJsonLd() {
  return { "@context": "https://schema.org", "@type": "WebSite", name: SITE.name, url: canonical(pathOf("home")), inLanguage: currentLocale(), publisher: { "@type": "Organization", name: COMPANY.legalName, url: content().cognera.home } };
}

/** The links that tell search engines about a page's language versions; none for a page without them. */
export function alternateLinks(path) {
  const route = routeOf(path);
  if (!route) return "";
  const links = alternates(route.key).map(({ locale, path: other }) => `<link rel="alternate" hreflang="${locale}" href="${canonical(other)}">`);
  links.push(`<link rel="alternate" hreflang="x-default" href="${canonical(pathOf(route.key, DEFAULT_LOCALE))}">`);
  return links.join("\n");
}

/**
 * A whole page in the current language. `path` is its address ("/forge/"), `meta` its title and description, `body`
 * the content of `main`, `head` extra head markup (a hero picture's preload), `jsonLd` structured data, `noindex`
 * keeps it out of search.
 */
export function page({ path, meta, body, head = "", jsonLd = [], noindex = false }) {
  need(path, "A page's path");
  need(meta?.title, `The title of ${path}`);
  need(meta?.description, `The description of ${path}`);
  need(body, `The body of ${path}`);
  const locale = currentLocale();
  const c = content();
  const title = fullTitle(path, meta.title);
  const url = canonical(path);
  const fonts = FONT_FILES.map((file) => `<link${attrs({ rel: "preload", href: `/assets/fonts/${file}`, as: "font", type: "font/woff2", crossorigin: true })}>`).join("\n");
  const data = jsonLd.map((item) => `<script type="application/ld+json">${jsonForScript(item)}</script>`).join("\n");
  const versions = noindex ? "" : alternateLinks(path);
  const otherLocales = Object.keys(OG_LOCALE).filter((l) => l !== locale && routeOf(path));
  return `<!doctype html>
${GENERATED_NOTE}
<html lang="${locale}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<meta name="description" content="${esc(meta.description)}">
${noindex ? '<meta name="robots" content="noindex">' : `<link rel="canonical" href="${esc(url)}">`}
${versions ? `${versions}\n` : ""}<meta property="og:type" content="website">
<meta property="og:site_name" content="${esc(SITE.name)}">
<meta property="og:locale" content="${OG_LOCALE[locale]}">
${otherLocales.map((l) => `<meta property="og:locale:alternate" content="${OG_LOCALE[l]}">\n`).join("")}<meta property="og:title" content="${esc(title)}">
<meta property="og:description" content="${esc(meta.description)}">
${noindex ? "" : `<meta property="og:url" content="${esc(url)}">\n`}<meta property="og:image" content="${SITE.origin}${SHARE_IMAGE[locale]}">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta name="twitter:card" content="summary_large_image">
<meta name="theme-color" content="#ffffff">
<meta name="color-scheme" content="light">
<link rel="icon" href="/favicon.svg" type="image/svg+xml">
<link rel="apple-touch-icon" href="/apple-touch-icon.png">
${fonts}
${head ? `${head}\n` : ""}<link rel="stylesheet" href="/assets/site.css?v=2">
<script>(function(d){d.classList.add("js");setTimeout(function(){if(!window.__siteReady)d.classList.remove("js")},4000)})(document.documentElement)</script>
<script>${HEAD_SCRIPT}</script>
<script type="module" src="/assets/js/site.js?v=2"></script>
${data}
</head>
<body>
<a class="skip-link" href="#obsah">${t(c.ui.skip)}</a>
${siteNav({ current: path })}
<main id="obsah">
${body}
</main>
${siteFooter()}
<script>${END_SCRIPT}</script>
<span id="${END_ID}" hidden></span>
</body>
</html>
`;
}

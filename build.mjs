#!/usr/bin/env node
/**
 * Builds the site: renders every page from src/ into plain files in the repository root, which GitHub Pages serves
 * as they are. No dependencies; Node 20 or newer.
 *
 *   node build.mjs           write the files
 *   node build.mjs --check   fail when a file on disk differs from a fresh build
 */
import { access, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { productMark } from "./src/components/product-mark.mjs";
import { media3dFiles } from "./src/content/media3d.mjs";
import { SCREEN_DIR, screenFiles } from "./src/content/screens.mjs";
import { referenceFiles } from "./src/content/references.mjs";
import { STORY_MEDIA, STORY_SCRIPTS } from "./src/content/story.mjs";
import { SITE } from "./src/content/site.mjs";
import { alternates } from "./src/i18n/index.mjs";
import { SHARE_IMAGE, canonical } from "./src/layout.mjs";
import { PAGES } from "./src/pages/index.mjs";
import { SCENE_MANIFESTS } from "./src/scenes.mjs";

export const ROOT = dirname(fileURLToPath(import.meta.url));

/** The styles in the order they are joined into assets/site.css: tokens, base, then one file per component. */
export const STYLES = [
  "tokens.css",
  "base.css",
  "site-nav.css",
  "site-footer.css",
  "screen-frame.css",
  "film.css",
  "hero.css",
  "tagline-reveal.css",
  "scroll-scene.css",
  "feature-list.css",
  "module-card.css",
  "module-story.css",
  "reference-showcase.css",
  "lang-transition.css",
  "step-sequence.css",
  "faq.css",
  "cta-band.css",
  "page-home.css",
  "page-prose.css",
];

/** Paths search engines have no business in: the site's source, served only because Pages publishes the whole repository. */
const NOT_FOR_CRAWLERS = ["/src/", "/tests/", "/build.mjs", "/package.json", "/README.md"];

async function styles() {
  const parts = await Promise.all(STYLES.map(async (name) => `/* ${name} */\n${(await readFile(join(ROOT, "src/styles", name), "utf8")).trim()}\n`));
  return `/* Generated by build.mjs from src/styles. Do not edit this file. */\n${parts.join("\n")}`;
}

function sitemap() {
  const urls = PAGES.filter((p) => p.inSitemap !== false).map((p) => {
    const versions = alternates(p.key).map(({ locale, path }) => `<xhtml:link rel="alternate" hreflang="${locale}" href="${canonical(path)}"/>`);
    return `  <url><loc>${canonical(p.path)}</loc>${versions.join("")}</url>`;
  });
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n${urls.join("\n")}\n</urlset>\n`;
}

function robots() {
  return `User-agent: *\nAllow: /\n${NOT_FOR_CRAWLERS.map((path) => `Disallow: ${path}`).join("\n")}\n\nSitemap: ${SITE.origin}/sitemap.xml\n`;
}

/** Every picture, film and scene frame the manifests name, as paths from the site root. */
export function mediaFiles() {
  const pad = (frame) => String(frame).padStart(3, "0");
  const scenes = Object.values(SCENE_MANIFESTS).flatMap((manifest) => [
    ...Object.values(manifest.sets).flatMap((set) => set.frames.flatMap((frame) => [`${set.base}/${pad(frame)}.avif`, `${set.base}/${pad(frame)}.webp`])),
    ...manifest.captionFrames.flatMap((_, k) => ["large", "small"].flatMap((cut) => [`${manifest.stills}/${cut}-${k + 1}.avif`, `${manifest.stills}/${cut}-${k + 1}.webp`])),
  ]);
  return [...screenFiles().map((file) => `${SCREEN_DIR}/${file}`), ...media3dFiles(), ...scenes, ...Object.values(SHARE_IMAGE), ...STORY_MEDIA, ...STORY_SCRIPTS, ...referenceFiles()];
}

/** Every generated file as [path relative to the root, content]. Throws when a page names a missing picture. */
export async function render() {
  for (const file of mediaFiles()) {
    try {
      await access(join(ROOT, file));
    } catch {
      throw new Error(`A manifest names a file that is not on disk: ${file}`);
    }
  }
  const out = new Map();
  for (const p of PAGES) {
    try {
      out.set(p.file, p.render());
    } catch (error) {
      throw new Error(`${p.file}: ${error.message}`, { cause: error });
    }
  }
  out.set("assets/site.css", await styles());
  out.set("sitemap.xml", sitemap());
  out.set("robots.txt", robots());
  out.set("favicon.svg", `${productMark("forge", { standalone: true })}\n`);
  return out;
}

/** The generated files whose content on disk differs from `files` (or is missing). */
export async function drift(files) {
  const changed = [];
  for (const [path, content] of files) {
    let current = null;
    try {
      current = await readFile(join(ROOT, path), "utf8");
    } catch {
      current = null;
    }
    if (current !== content) changed.push(path);
  }
  return changed;
}

async function main() {
  const files = await render();
  if (process.argv.includes("--check")) {
    const changed = await drift(files);
    if (changed.length > 0) {
      console.error(`Out of date (run \`node build.mjs\`):\n${changed.map((path) => `  ${path}`).join("\n")}`);
      process.exitCode = 1;
      return;
    }
    console.log(`Up to date: ${files.size} files.`);
    return;
  }
  for (const [path, content] of files) {
    await mkdir(dirname(join(ROOT, path)), { recursive: true });
    await writeFile(join(ROOT, path), content);
  }
  console.log(`Built ${files.size} files.`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
